#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'config', 'sites.json'), 'utf8'));
const sites = (config.sites || []).filter((site) => site.enabled).map((site) => ({
  id: site.id,
  label: site.alertLabel || site.name,
  origins: site.storefrontOrigins || [new URL(site.baseUrl).origin],
  baseUrl: site.baseUrl,
  repository: site.repository,
  repositoryId: String(site.repositoryId),
  branchRef: `refs/heads/${site.defaultBranch}`,
  enabledLayers: (site.layers || []).map((layer) => `layer${layer}`),
}));
const output = `// Generated by scripts/generate-worker-sites.mjs. Do not edit manually.\nexport const MONITOR_SITES = ${JSON.stringify(sites, null, 2)};\n`;
const outputPath = path.join(root, 'workers', 'site-catalog.generated.mjs');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) throw new Error('TEST_CONFIG_STALE: workers/site-catalog.generated.mjs is not synchronized with config/sites.json');
  console.log('Worker site catalog is synchronized.');
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated ${path.relative(root, outputPath)} for ${sites.length} site(s).`);
}
